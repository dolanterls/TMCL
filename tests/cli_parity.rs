/// `help` is generated by clap and is not part of our surface. There is no
/// generated `version` subcommand: `--version` is a flag, and `version` is a
/// real command of ours.
fn is_builtin(name: &str) -> bool {
    name == "help"
}

/// Every leaf of the command tree, with the path that reaches it.
fn leaves() -> Vec<(Vec<String>, Command)> {
    let mut root = Cli::command();
    root.build();
    let mut collected = Vec::new();
    collect(&root, &mut Vec::new(), &mut collected);
    collected
}

fn collect(command: &Command, path: &mut Vec<String>, out: &mut Vec<(Vec<String>, Command)>) {
    let children = command
        .get_subcommands()
        .filter(|child| !is_builtin(child.get_name()))
        .cloned()
        .collect::<Vec<_>>();
    if children.is_empty() {
        out.push((path.clone(), command.clone()));
        return;
    }
    for child in children {
        path.push(child.get_name().to_owned());
        collect(&child, path, out);
        path.pop();
    }
}

fn argv_for(path: &[String], extra: &[&str]) -> Vec<String> {
    let mut argv = vec!["tmcl".to_owned()];
    argv.extend(path.iter().cloned());
    argv.extend(extra.iter().map(|value| (*value).to_owned()));
    argv
}

fn exists(leaves: &[(Vec<String>, Command)], path: &[&str]) -> bool {
    leaves.iter().any(|(candidate, _)| {
        candidate
            .iter()
            .map(String::as_str)
            .eq(path.iter().copied())
    })
}

#[test]
fn the_tree_still_has_every_command_we_expect() {
    let leaves = leaves();
    // An exact count on purpose: adding a command without adding it to
    // `docs/superpowers/references/cli-core-map.md` should be a decision, not a
    // silent diff. Bump this number in the same commit as the new row.
    assert_eq!(
        leaves.len(),
        67,
        "leaf count changed; update `cli-core-map.md` and this number: {:?}",
        leaves
            .iter()
            .map(|(path, _)| path.join(" "))
            .collect::<Vec<_>>()
    );
}

#[test]
fn every_command_explains_itself() {
    let mut missing = Vec::new();
    for (path, command) in leaves() {
        let about = command
            .get_about()
            .map(|about| about.to_string())
            .unwrap_or_default();
        if about.trim().is_empty() {
            missing.push(path.join(" "));
        }
    }
    assert!(missing.is_empty(), "no about text for: {missing:?}");
}

#[test]
fn every_command_accepts_the_global_json_flag() {
    let mut rejected = Vec::new();
    for (path, _) in leaves() {
        // Parsed through the root: global arguments live there and are only
        // merged in during a real parse, so asking the leaf on its own would
        // report a false negative.
        let argv = argv_for(&path, &["--json"]);
        match Cli::try_parse_from(&argv) {
            Ok(_) => {}
            Err(error) => {
                // A required positional still has to be supplied; what must not
                // happen is `--json` being rejected as an unknown argument.
                if error.kind() == ErrorKind::UnknownArgument {
                    rejected.push(path.join(" "));
                }
            }
        }
    }
    assert!(
        rejected.is_empty(),
        "--json is not global for: {rejected:?}"
    );
}

fn find<'a>(leaves: &'a [(Vec<String>, Command)], path: &[&str]) -> &'a Command {
    leaves
        .iter()
        .find(|(candidate, _)| {
            candidate
                .iter()
                .map(String::as_str)
                .eq(path.iter().copied())
        })
        .map(|(_, command)| command)
        .expect("the parity lists are checked against the tree first")
}

#[test]
fn destructive_commands_offer_yes_and_dry_run() {
    let leaves = leaves();
    for path in DESTRUCTIVE {
        let command = find(&leaves, path);
        assert!(
            command
                .get_arguments()
                .any(|argument| argument.get_id() == "yes"),
            "{} cannot be confirmed with --yes",
            path.join(" ")
        );
        let argv = argv_for(
            &path.iter().map(|s| (*s).to_owned()).collect::<Vec<_>>(),
            &["--dry-run"],
        );
        match Cli::try_parse_from(&argv) {
            Ok(_) => {}
            Err(error) => assert_ne!(
                error.kind(),
                ErrorKind::UnknownArgument,
                "{} does not accept --dry-run",
                path.join(" ")
            ),
        }
    }
}

#[test]
fn instance_scoped_commands_accept_a_reference() {
    let leaves = leaves();
    for path in INSTANCE_SCOPED {
        let command = find(&leaves, path);
        assert!(
            command
                .get_positionals()
                .any(|argument| argument.get_id() == "reference"),
            "{} has no [REF] positional",
            path.join(" ")
        );
    }
}

#[test]
fn the_parity_lists_only_name_commands_that_exist() {
    let leaves = leaves();
    for path in DESTRUCTIVE.iter().chain(INSTANCE_SCOPED).chain(PLAIN) {
        assert!(
            exists(&leaves, path),
            "the parity list names a command that does not exist: {}",
            path.join(" ")
        );
    }
}

/// Same path, both as slices, ignoring allocation differences.
fn same(left: &[&str], right: &[String]) -> bool {
    left.len() == right.len() && left.iter().zip(right).all(|(a, b)| a == b)
}

#[test]
fn every_leaf_is_classified() {
    let leaves = leaves();
    let mut unclassified = Vec::new();
    for (path, _) in &leaves {
        let classified = DESTRUCTIVE.iter().any(|entry| same(entry, path))
            || INSTANCE_SCOPED.iter().any(|entry| same(entry, path))
            || PLAIN.iter().any(|entry| same(entry, path));
        if !classified {
            unclassified.push(path.join(" "));
        }
    }
    assert!(
        unclassified.is_empty(),
        "these commands are not in DESTRUCTIVE, INSTANCE_SCOPED or PLAIN; \
         decide what they are and add them: {unclassified:?}"
    );
}

#[test]
fn the_plain_list_is_disjoint_from_the_other_two() {
    for path in PLAIN {
        assert!(
            !DESTRUCTIVE.iter().any(|entry| entry == path),
            "{} is both plain and destructive",
            path.join(" ")
        );
        assert!(
            !INSTANCE_SCOPED.iter().any(|entry| entry == path),
            "{} is both plain and instance-scoped",
            path.join(" ")
        );
    }
}

#[test]
fn no_path_is_listed_twice_in_one_list() {
    for (name, list) in [
        ("DESTRUCTIVE", DESTRUCTIVE),
        ("INSTANCE_SCOPED", INSTANCE_SCOPED),
        ("PLAIN", PLAIN),
    ] {
        let mut seen = std::collections::BTreeSet::new();
        for path in list {
            assert!(seen.insert(path.join(" ")), "{name} lists a path twice");
        }
    }
}
